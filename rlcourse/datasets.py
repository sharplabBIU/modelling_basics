def _questionnaire(z, rng, lo, hi, mean, sd, noise_sd):
    """Map a standardised latent score z into a bounded questionnaire-like score."""
    score = mean + sd * (z + rng.normal(0, noise_sd, size=len(z))) / np.sqrt(1 + noise_sd ** 2)
    return np.clip(np.round(score), lo, hi).astype(int)


def make_two_step_compulsivity(n_subjects=60, n_trials=200, seed=11):
    rng = np.random.default_rng(seed)
    z_comp = rng.normal(size=n_subjects)
    # model-based weight w decreases with compulsivity (in logit space)
    w = models.sigmoid(0.4 - 0.9 * z_comp + rng.normal(0, 0.5, n_subjects))
    truth = pd.DataFrame({
        "subject": np.arange(n_subjects),
        "alpha1": rng.beta(4, 4, n_subjects),
        "alpha2": rng.beta(4, 4, n_subjects),
        "lam": rng.beta(5, 3, n_subjects),
        "beta1": np.exp(rng.normal(np.log(4.0), 0.3, n_subjects)),
        "beta2": np.exp(rng.normal(np.log(4.0), 0.3, n_subjects)),
        "w": w,
        "p": rng.normal(0.15, 0.1, n_subjects),
    })
    subjects = pd.DataFrame({
        "subject": np.arange(n_subjects),
        "age": rng.integers(18, 45, n_subjects),
        "compulsivity": _questionnaire(z_comp, rng, 0, 72, 22, 12, 0.6),
        "anxiety": _questionnaire(rng.normal(size=n_subjects), rng, 20, 80, 40, 10, 0.6),
    })
    rows = []
    for i in range(n_subjects):
        task = tasks.TwoStepTask(n_trials=n_trials, rng=rng)
        params = truth.loc[i, models.TWO_STEP_PARAM_NAMES].to_numpy(float)
        d = models.two_step_simulate(params, task, rng)
        rows.append(pd.DataFrame({"subject": i, "trial": np.arange(n_trials), "a1": d["a1"],
                                  "s2": d["s2"], "a2": d["a2"], "r": d["r"].astype(int),
                                  "common": d["common"]}))
    return pd.concat(rows, ignore_index=True), subjects, truth


def make_reversal_anxiety(n_subjects=60, seed=12):
    rng = np.random.default_rng(seed)
    z_anx = rng.normal(size=n_subjects)
    alpha_stable = models.sigmoid(rng.normal(-1.4, 0.4, n_subjects))                 # ~0.2
    # adaptation = volatile - stable learning rate (logit units); smaller for anxious people
    adaptation = np.clip(1.2 - 0.7 * z_anx + rng.normal(0, 0.35, n_subjects), 0.0, None)
    alpha_volatile = models.sigmoid(models.logit(alpha_stable) + adaptation)
    beta = np.exp(rng.normal(np.log(5.0), 0.3, n_subjects))
    truth = pd.DataFrame({"subject": np.arange(n_subjects), "alpha_stable": alpha_stable,
                          "alpha_volatile": alpha_volatile, "beta": beta})
    subjects = pd.DataFrame({
        "subject": np.arange(n_subjects),
        "age": rng.integers(18, 45, n_subjects),
        "trait_anxiety": _questionnaire(z_anx, rng, 20, 80, 42, 11, 0.6),
        "compulsivity": _questionnaire(rng.normal(size=n_subjects), rng, 0, 72, 20, 12, 0.6),
    })
    rows = []
    for i in range(n_subjects):
        volatile_first = bool(i % 2)
        task = tasks.ReversalTask.stable_volatile(rng=rng, volatile_first=volatile_first)
        p_hat = 0.5
        choices = np.zeros(task.n_trials, int)
        outcomes = np.zeros(task.n_trials, int)
        rewards = np.zeros(task.n_trials)
        for t in range(task.n_trials):
            alpha = alpha_volatile[i] if task.block[t] == "volatile" else alpha_stable[i]
            p0 = models.sigmoid(beta[i] * (2 * p_hat - 1))
            c = 0 if rng.random() < p0 else 1
            r, o = task.step(c)
            p_hat = p_hat + alpha * (o - p_hat)
            choices[t], outcomes[t], rewards[t] = c, o, r
        rows.append(pd.DataFrame({"subject": i, "trial": np.arange(task.n_trials), "block": task.block,
                                  "choice": choices, "outcome": outcomes, "reward": rewards.astype(int),
                                  "p_option0": task.schedule}))
    return pd.concat(rows, ignore_index=True), subjects, truth


def make_bandit_anhedonia(n_subjects=80, n_trials=160, seed=13):
    rng = np.random.default_rng(seed)
    z_anh = rng.normal(size=n_subjects)
    alpha_pos = models.sigmoid(rng.normal(-0.4, 0.4, n_subjects) - 0.8 * z_anh)
    alpha_neg = models.sigmoid(rng.normal(-0.9, 0.4, n_subjects))
    beta = np.exp(rng.normal(np.log(4.0), 0.3, n_subjects))
    truth = pd.DataFrame({"subject": np.arange(n_subjects), "alpha_pos": alpha_pos,
                          "alpha_neg": alpha_neg, "beta": beta})
    subjects = pd.DataFrame({
        "subject": np.arange(n_subjects),
        "age": rng.integers(18, 45, n_subjects),
        "anhedonia": _questionnaire(z_anh, rng, 0, 56, 18, 9, 0.6),
        "anxiety": _questionnaire(rng.normal(size=n_subjects), rng, 20, 80, 40, 10, 0.6),
    })
    probs = np.array([[0.7, 0.3]] * (n_trials // 2) + [[0.3, 0.7]] * (n_trials - n_trials // 2))
    rows = []
    for i in range(n_subjects):
        Q = np.full(2, 0.5)
        choices = np.zeros(n_trials, int)
        rewards = np.zeros(n_trials)
        for t in range(n_trials):
            p = models.softmax(Q, beta[i])
            c = models.choose(p, rng)
            r = float(rng.random() < probs[t, c])
            delta = r - Q[c]
            Q[c] += (alpha_pos[i] if delta > 0 else alpha_neg[i]) * delta
            choices[t], rewards[t] = c, r
        rows.append(pd.DataFrame({"subject": i, "trial": np.arange(n_trials), "choice": choices,
                                  "reward": rewards.astype(int), "p_arm0": probs[:, 0]}))
    return pd.concat(rows, ignore_index=True), subjects, truth


GENERATORS = {
    "two_step_compulsivity": make_two_step_compulsivity,
    "reversal_anxiety": make_reversal_anxiety,
    "bandit_anhedonia": make_bandit_anhedonia,
}


def make_all(verbose: bool = True) -> None:
    os.makedirs(DATA_DIR, exist_ok=True)
    for name, gen in GENERATORS.items():
        trials, subjects, truth = gen()
        trials.to_csv(_path(name), index=False)
        subjects.to_csv(_path(name, "_subjects"), index=False)
        truth.to_csv(_path(name, "_truth"), index=False)
        if verbose:
            print(f"{name}: {len(trials)} trials, {len(subjects)} subjects")


__all__ = ["load", "truth", "describe", "split_by_subject", "make_all", "DESCRIPTIONS", "DATA_DIR"]
