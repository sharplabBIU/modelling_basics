"""Synthetic "participant" data sets used in lessons 9, 12, 13, 14 and 15.

All data are *simulated* from the models taught in the course (the generating
parameters are stored in ``data/<name>_truth.csv`` so that lessons can reveal
them).  The symptom scores are simulated too; the relations built into them
are *inspired by* published findings (see the lesson notebooks), they are not
real data.

    from rlcourse import datasets
    trials, subjects = datasets.load("two_step_compulsivity")
    truth = datasets.truth("two_step_compulsivity")

Regenerate everything with ``python scripts/make_datasets.py``.
"""
from __future__ import annotations

import os

import numpy as np
import pandas as pd

from . import models, tasks

DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")

DESCRIPTIONS = {
    "two_step_compulsivity": (
        "60 simulated participants x 200 trials of the two-step task (Daw et al. 2011), "
        "generated by the hybrid MB/MF model.  The 'compulsivity' questionnaire score is "
        "built to correlate negatively with the model-based weight w (cf. Gillan et al. 2016); "
        "'anxiety' is unrelated to any parameter."),
    "reversal_anxiety": (
        "60 simulated participants x 240 trials of a stable/volatile reversal task "
        "(Behrens et al. 2007 design), generated by a Rescorla-Wagner learner with a "
        "separate learning rate in each block.  The 'trait_anxiety' score is built to "
        "correlate negatively with the volatile-minus-stable learning-rate difference "
        "(cf. Browning et al. 2015)."),
    "bandit_anhedonia": (
        "80 simulated participants x 160 trials of a two-armed bandit with one reversal, "
        "generated by a Rescorla-Wagner model with separate learning rates for positive "
        "and negative prediction errors.  The 'anhedonia' score is built to correlate "
        "negatively with the positive learning rate (cf. the positivity-bias literature, "
        "Lefebvre et al. 2017; Pulcu & Browning 2017)."),
}


def _path(name: str, suffix: str = "") -> str:
    return os.path.join(DATA_DIR, f"{name}{suffix}.csv")


def load(name: str):
    """Return ``(trials, subjects)`` data frames for a data set."""
    if name not in DESCRIPTIONS:
        raise KeyError(f"unknown data set {name!r}; choose from {list(DESCRIPTIONS)}")
    trials = pd.read_csv(_path(name))
    subjects = pd.read_csv(_path(name, "_subjects"))
    return trials, subjects


def truth(name: str):
    """The generating parameters of each simulated participant."""
    return pd.read_csv(_path(name, "_truth"))


def describe(name: str) -> str:
    return DESCRIPTIONS[name]


def split_by_subject(trials: pd.DataFrame, columns=None) -> dict:
    """``{subject: {column: array}}`` for quick per-subject model fitting."""
    columns = [c for c in trials.columns if c not in ("subject", "trial")] if columns is None else columns
    out = {}
    for subj, df in trials.groupby("subject", sort=True):
        out[int(subj)] = {c: df[c].to_numpy() for c in columns}
    return out


